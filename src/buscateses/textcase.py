@dataclass(frozen=True)
class _Lexicon:
    """Immutable lexicon loaded from ``data/truecase.json``."""

    acronyms: frozenset[str]
    proper: Mapping[str, str]
    accents: Mapping[str, str]


_EMPTY_LEXICON = _Lexicon(frozenset(), {}, {})


def _fold(text: str) -> str:
    """Return lowercase text without diacritics (lexicon lookup key)."""
    decomposed = unicodedata.normalize("NFD", text)
    stripped = "".join(char for char in decomposed if not unicodedata.combining(char))
    return stripped.casefold()


def _has_accent(text: str) -> bool:
    """Return True if *text* contains at least one accented letter."""
    for char in text:
        if not char.isalpha():
            continue
        decomposed = unicodedata.normalize("NFD", char)
        if any(unicodedata.combining(part) for part in decomposed[1:]):
            return True
    return False


@lru_cache(maxsize=1)
def _load_lexicon() -> _Lexicon:
    """Load and cache the bundled truecase lexicon (empty if unavailable)."""
    try:
        location = resources.files("buscateses").joinpath("data/truecase.json")
        with resources.as_file(location) as path:
            raw = json.loads(path.read_text(encoding="utf-8"))
    except (FileNotFoundError, ModuleNotFoundError, OSError, TypeError, ValueError):
        return _EMPTY_LEXICON
    if not isinstance(raw, dict):
        return _EMPTY_LEXICON
    acronyms = frozenset(
        _fold(str(item)) for item in raw.get("acronyms", []) if str(item).strip()
    )
    proper = {
        _fold(str(key)): str(value)
        for key, value in dict(raw.get("proper", {})).items()
        if str(key).strip() and str(value).strip()
    }
    accents = {
        _fold(str(key)): str(value)
        for key, value in dict(raw.get("accents", {})).items()
        if str(key).strip() and str(value).strip()
    }
    return _Lexicon(acronyms=acronyms, proper=proper, accents=accents)


def is_shouting(text: str | None) -> bool:
    """Return True for mostly-uppercase text with at least eight letters."""
    if not text:
        return False
    letters = 0
    uppercase = 0
    for char in text:
        if char.isalpha():
            letters += 1
            if char.isupper():
                uppercase += 1
    return letters >= SHOUTING_MIN_LETTERS and uppercase / letters >= SHOUTING_UPPER_RATIO


def _is_short_shouting(text: str | None, lexicon: _Lexicon) -> bool:
    """Return True for a short value written entirely in uppercase.

    Unlike :func:`is_shouting`, this applies to values with as few as three
    letters, which is how short fields such as ``DIREITO`` and ``SUDESTE``
    reach the interface.  Known acronyms, values containing digits and values
    listed in the lexicon are never converted.
    """
    if not text:
        return False
    letters = 0
    for char in text:
        if not char.isalpha():
            continue
        letters += 1
        if not char.isupper():
            return False
    if letters < SHORT_SHOUTING_MIN_LETTERS:
        return False
    if any(char.isdigit() for char in text):
        return False
    return _fold(text.strip()) not in lexicon.acronyms


def _is_kept_acronym(part: str, lexicon: _Lexicon) -> bool:
    """Return True for a known acronym or a Brazilian state code."""
    key = _fold(part)
    return key in lexicon.acronyms or (part.isupper() and part.upper() in _UF_CODES)



def _is_roman_numeral(part: str) -> bool:
    """Return True for a valid roman numeral of two or more letters."""
    upper = part.upper()
    return len(upper) >= 2 and bool(_ROMAN_RE.fullmatch(upper))


def _convert_part(part: str, lexicon: _Lexicon, restore_accents: bool) -> str:
    """Convert a single alphanumeric part (no hyphen/apostrophe separator)."""
    if not part:
        return part
    if any(char.isdigit() for char in part):
        return part
    key = _fold(part)
    if _is_kept_acronym(part, lexicon):
        return part.upper()
    if _is_roman_numeral(part):
        return part.upper()
    if restore_accents:
        word = lexicon.accents.get(key, part.lower())
    else:
        word = part.lower()
    return lexicon.proper.get(key, word)


def _convert_chunk(chunk: str, lexicon: _Lexicon, restore_accents: bool) -> str:
    """Convert one word chunk, keeping hyphens/apostrophes in place."""
    if any(char.isdigit() for char in chunk):
        return chunk
    pieces: list[str] = []
    for piece in _PART_SPLIT_RE.split(chunk):
        if piece in {"-", "'"}:
            pieces.append(piece)
        else:
            pieces.append(_convert_part(piece, lexicon, restore_accents))
    return "".join(pieces)


def _rewrite_chunks(text: str, convert: Any) -> str:
    """Apply *convert* to every word chunk, preserving all separators."""
    pieces: list[str] = []
    cursor = 0
    for match in _CHUNK_RE.finditer(text):
        pieces.append(text[cursor : match.start()])
        pieces.append(convert(match.group(0)))
        cursor = match.end()
    pieces.append(text[cursor:])
    return "".join(pieces)


def _capitalize_chunk(chunk: str) -> str:
    """Uppercase the first alphabetic character of a word chunk."""
    for index, char in enumerate(chunk):
        if char.isalpha():
            return chunk[:index] + char.upper() + chunk[index + 1 :]
    return chunk


def _apply_compound_toponyms(text: str, lexicon: _Lexicon) -> str:
    """Capitalize ambiguous first words of compound Brazilian toponyms.

    ``SÃO PAULO`` and ``RIO GRANDE DO SUL`` must survive sentence casing even
    though ``são`` and ``rio`` are also common words.  A trigger word is only
    promoted when the next word (optionally after ``de``/``do``/``da``) is a
    lexicon proper name or a known toponym complement, so phrases such as
    ``são analisados`` and ``o rio principal`` stay untouched.
    """
    matches = list(_CHUNK_RE.finditer(text))
    if not matches:
        return text
    chunks = [match.group(0) for match in matches]
    keys = [_fold(chunk) for chunk in chunks]
    capitalize: set[int] = set()
    for index, key in enumerate(keys):
        if key not in _TOPONYM_FIRST:
            continue
        cursor = index + 1
        while cursor < len(keys) and keys[cursor] in _TOPONYM_LINKERS:
            cursor += 1
        if cursor >= len(keys):
            continue
        next_key = keys[cursor]
        if next_key not in lexicon.proper and next_key not in _TOPONYM_TAILS:
            continue
        capitalize.add(index)
        # Follow the compound through complements and linkers so that the
        # "Sul" in "Rio Grande do Sul" and the "Fora" in "Juiz de Fora" are
        # promoted as well.
        while cursor < len(keys):
            current = keys[cursor]
            if current in lexicon.proper:
                cursor += 1
                continue
            if current in _TOPONYM_TAILS:
                capitalize.add(cursor)
                cursor += 1
                continue
            if current in _TOPONYM_LINKERS:
                cursor += 1
                continue
            break
    if not capitalize:
        return text
    pieces: list[str] = []
    cursor = 0
    for index, match in enumerate(matches):
        pieces.append(text[cursor : match.start()])
        chunk = match.group(0)
        pieces.append(_capitalize_chunk(chunk) if index in capitalize else chunk)
        cursor = match.end()
    pieces.append(text[cursor:])
    return "".join(pieces)


def _short_abbreviation_before(characters: list[str], index: int) -> bool:
    """Return True when the word before ``index`` looks like an abbreviation.

    Only short alphabetic words (up to four letters) count, and common words
    that legitimately end a sentence are excluded, so ``fim. Outro`` still
    capitalizes while ``spp. Ocorrentes`` does not.
    """
    letters: list[str] = []
    cursor = index - 1
    while cursor >= 0 and characters[cursor] in _TERMINALS:
        cursor -= 1
    while cursor >= 0:
        char = characters[cursor]
        if char.isalpha():
            letters.append(char)
            cursor -= 1
            continue
        if char.isdigit():
            return False
        break
    if not letters:
        return False
    word = "".join(reversed(letters))
    return len(word) <= 4 and _fold(word) not in _SENTENCE_END_SHORT_WORDS


def _capitalize_sentences(text: str, capitalize_first: bool) -> str:
    """Capitalize the first letter and letters after ``. ! ?`` + space."""
    if not text:
        return text
    characters = list(text)
    capitalize_next = capitalize_first
    pending_terminal = False
    for index, char in enumerate(characters):
        if char.isalpha():
            if capitalize_next:
                characters[index] = char.upper()
            capitalize_next = False
            pending_terminal = False
        elif char in _TERMINALS:
            # A dot between digits (e.g. ``1.5``) is a decimal separator.
            decimal = (
                0 < index < len(characters) - 1
                and characters[index - 1].isdigit()
                and characters[index + 1].isdigit()
            )
            pending_terminal = not decimal
        elif char.isspace():
            if pending_terminal and not _short_abbreviation_before(characters, index):
                capitalize_next = True
            pending_terminal = False
        else:
            # A terminal only ends a sentence when followed by whitespace;
            # abbreviations such as ``n.°`` must not capitalize the next word.
            pending_terminal = False
    return "".join(characters)


def _protect_parenthetical_acronyms(text: str) -> tuple[str, list[str]]:
    """Replace short uppercase parentheticals with sentinels for later restore."""
    kept: list[str] = []

    def replace(match: re.Match[str]) -> str:
        inner = match.group(1)
        if not inner.isupper():
            return match.group(0)
        kept.append(inner.upper())
        return f"(\x00{len(kept) - 1}\x00)"

    return _PAREN_ACRONYM_RE.sub(replace, text), kept


def _restore_parenthetical_acronyms(text: str, kept: list[str]) -> str:
    """Restore the acronyms protected by :func:`_protect_parenthetical_acronyms`."""
    if not kept:
        return text
    return _SENTINEL_RE.sub(lambda match: kept[int(match.group(1))], text)



def _letter_count(text: str) -> int:
    """Return the number of alphabetic characters in *text*."""
    return sum(1 for char in text if char.isalpha())


def _keep_ambiguous_uf(prefix: str, previous_part: str | None, lexicon: _Lexicon) -> bool:
    """Decide whether an ambiguous state code (``SE``) is really a place."""
    if previous_part is not None:
        return _fold(previous_part) in lexicon.proper
    return bool(_PLACE_SEPARATOR_RE.search(prefix))


def _convert_prose_chunk(
    chunk: str, prefix: str, lexicon: _Lexicon, restore_accents: bool
) -> str:
    """Like :func:`_convert_chunk`, but resolves ``SE`` (pronoun vs. Sergipe)."""
    if any(char.isdigit() for char in chunk):
        return chunk
    pieces: list[str] = []
    previous: str | None = None
    for piece in _PART_SPLIT_RE.split(chunk):
        if piece in {"-", "'"}:
            pieces.append(piece)
            continue
        if piece.upper() in _PROSE_AMBIGUOUS_UFS:
            if _keep_ambiguous_uf(prefix, previous, lexicon):
                pieces.append(piece.upper())
            else:
                pieces.append(piece.lower())
        else:
            pieces.append(_convert_part(piece, lexicon, restore_accents))
        if piece:
            previous = piece
    return "".join(pieces)


def _rewrite_prose_chunks(text: str, lexicon: _Lexicon, restore_accents: bool) -> str:
    """Convert every chunk of shouting prose, with left context for ``SE``."""
    pieces: list[str] = []
    cursor = 0
    for match in _CHUNK_RE.finditer(text):
        pieces.append(text[cursor : match.start()])
        pieces.append(
            _convert_prose_chunk(
                match.group(0), text[max(0, match.start() - 4) : match.start()], lexicon, restore_accents
            )
        )
        cursor = match.end()
    pieces.append(text[cursor:])
    return "".join(pieces)


def _truecase_shouting(text: str, *, capitalize_first: bool) -> str:
    """Convert an all-uppercase fragment to readable sentence case."""
    lexicon = _load_lexicon()
    restore_accents = not _has_accent(text)

    masked, acronyms = _protect_parenthetical_acronyms(text)
    converted = _rewrite_prose_chunks(masked, lexicon, restore_accents)
    converted = _apply_compound_toponyms(converted, lexicon)
    converted = _capitalize_sentences(converted, capitalize_first)
    return _restore_parenthetical_acronyms(converted, acronyms)


def _is_convertible_segment(segment: str) -> bool:
    """Return True for a long uppercase fragment worth truecasing."""
    return (
        _letter_count(segment) >= SEGMENT_SHOUTING_MIN_LETTERS
        and is_shouting(segment)
    )


def _truecase_segments(text: str, *, capitalize_first: bool) -> str | None:
    """Truecase shouting fragments inside an otherwise mixed-case text.

    Catalogue titles occasionally mix a long uppercase fragment with a
    normally cased one, for example ``... RIO GRANDE DO SUL. Um modelo para o
    cultivo``.  Fragments separated by sentence-like punctuation are converted
    one by one only when the text is genuinely mixed; fragments already in
    normal case are preserved exactly, and short uppercase fragments (acronyms,
    abbreviations) are left alone.

    Returns ``None`` when *text* has no mixture to handle, so callers can fall
    back to the whole-text rules.
    """
    parts = _SEGMENT_SEPARATOR_RE.split(text)
    if len(parts) == 1:
        return None
    segments = parts[0::2]
    convertible = [_is_convertible_segment(segment) for segment in segments]
    if not any(convertible):
        return None
    # Only mixed titles qualify: at least one fragment must already be in
    # normal case (it contains lowercase letters).  Otherwise the whole-title
    # rules apply, including short uppercase fragments.
    if not any(
        segment.strip() and any(char.islower() for char in segment)
        for segment in segments
    ):
        return None
    converted: list[str] = []
    for index, part in enumerate(parts):
        if index % 2 == 1:  # separator captured by the split
            converted.append(part)
        elif convertible[index // 2]:
            converted.append(
                _truecase_shouting(part, capitalize_first=capitalize_first)
            )
        else:
            converted.append(part)
    return "".join(converted)


def truecase(text: str | None, *, capitalize_first: bool = True) -> str:
    """Return readable sentence case for *text*.

    Texts that are not shouting are normally returned byte-for-byte unchanged.
    As an exception, a long shouting fragment inside an otherwise mixed-case
    text is converted on its own (see :func:`_truecase_segments`).  In shouting
    texts, acronyms, numbers, roman numerals and proper names are preserved,
    and accents are restored for legacy unaccented records.
    """
    if text is None:
        return ""
    segmented = _truecase_segments(text, capitalize_first=capitalize_first)
    if segmented is not None:
        return segmented
    if is_shouting(text):
        return _truecase_shouting(text, capitalize_first=capitalize_first)
    return text


def _name_part(part: str, lexicon: _Lexicon, restore_accents: bool, at_start: bool) -> str:
    """Title-case one name part, respecting particles and acronyms."""
    if not part:
        return part
    if any(char.isdigit() for char in part):
        return part
    key = _fold(part)
    if _is_kept_acronym(part, lexicon):
        return part.upper()
    if _is_roman_numeral(part):
        return part.upper()
    if restore_accents:
        word = lexicon.accents.get(key, part.lower())
    else:
        word = part.lower()
    if key in _PARTICLES and not at_start:
        return word
    return word[:1].upper() + word[1:]


def _name_segment(segment: str, lexicon: _Lexicon, restore_accents: bool) -> str:
    """Title-case one semicolon-delimited name list item."""
    seen_word = False

    def convert(chunk: str) -> str:
        nonlocal seen_word
        if any(char.isdigit() for char in chunk):
            seen_word = True
            return chunk
        pieces: list[str] = []
        for piece in _PART_SPLIT_RE.split(chunk):
            if piece in {"-", "'"}:
                pieces.append(piece)
                continue
            pieces.append(_name_part(piece, lexicon, restore_accents, not seen_word))
            if piece:
                seen_word = True
        return "".join(pieces)

    return _rewrite_chunks(segment, convert)


def _name_item(segment: str, lexicon: _Lexicon, force_short: bool = False) -> str:
    """Title-case one list item, ignoring trailing parenthetical annotations."""
    match = re.match(r"^(.*?)(\s*\([^)]*\)\s*)$", segment, re.DOTALL)
    core = match.group(1) if match else segment
    suffix = (match.group(2) or "") if match else ""
    shouting = is_shouting(core) or _is_short_shouting(core, lexicon)
    if not shouting and not force_short:
        return segment
    if not shouting:
        # The record itself is shouting, but this item is not; leave it alone.
        return segment
    restore_accents = not _has_accent(core)
    return _name_segment(core, lexicon, restore_accents) + suffix


def name_case(text: str | None, *, force_short: bool = False) -> str:
    """Return title casing for names, institutions, programs and areas.

    Semicolon-separated lists are handled item by item.  Particles such as
    ``de``/``da`` stay lowercase except at the start of an item, acronyms from
    the lexicon stay uppercase, and accents are restored for legacy records.
    Short all-uppercase values (``DIREITO``, ``SUDESTE``) are converted too;
    ``force_short`` applies the same rule when the surrounding record is
    shouting.  Trailing annotations such as ``(coorientador)`` are preserved.
    """
    if text is None:
        return ""
    lexicon = _load_lexicon()
    pieces = re.split(r"(;)", text)
    converted: list[str] = []
    for piece in pieces:
        if piece == ";":
            converted.append(piece)
        else:
            converted.append(_name_item(piece, lexicon, force_short))
    return "".join(converted)


def _sentence_case(text: str, lexicon: _Lexicon) -> str:
    """Convert an all-uppercase fragment to sentence case."""
    restore_accents = not _has_accent(text)
    converted = _rewrite_chunks(
        text, lambda chunk: _convert_chunk(chunk, lexicon, restore_accents)
    )
    converted = _apply_compound_toponyms(converted, lexicon)
    return _capitalize_sentences(converted, True)


def _keywords_case(
    value: str, lexicon: _Lexicon, force_short: bool = False
) -> str:
    """Truecase each semicolon-separated keyword independently."""
    del force_short  # short items are always converted by their own rule
    items = [item.strip() for item in value.split(";")]
    converted: list[str] = []
    for item in items:
        if not item:
            continue
        if is_shouting(item):
            converted.append(truecase(item, capitalize_first=True))
        elif _is_short_shouting(item, lexicon):
            converted.append(_sentence_case(item, lexicon))
        else:
            converted.append(item)
    return "; ".join(converted) if converted else value


def display_record(record: Mapping[str, Any]) -> dict[str, Any]:
    """Return a copy of *record* with display-friendly text fields.

    Titles and abstracts go through :func:`truecase`; keywords are handled item
    by item; people, institutions, programs and areas go through
    :func:`name_case`.  English fields, URLs, identifiers and numbers are left
    untouched.
    """
    data: dict[str, Any] = dict(record)
    for field in ("title", "abstract"):
        value = data.get(field)
        if isinstance(value, str):
            data[field] = truecase(value)
    # When the record itself is shouting (title or abstract), short values in
    # the other fields are shouting too and must not be left untouched.
    title = data.get("title")
    abstract = data.get("abstract")
    force_short = is_shouting(title if isinstance(title, str) else None) or is_shouting(
        abstract if isinstance(abstract, str) else None
    )
    lexicon = _load_lexicon()
    keywords = data.get("keywords")
    if isinstance(keywords, str):
        data["keywords"] = _keywords_case(keywords, lexicon, force_short)
    for field in _NAME_FIELDS:
        value = data.get(field)
        if isinstance(value, str):
            data[field] = name_case(_tidy_parentheses(value), force_short=force_short)
    library = data.get("library")
    if isinstance(library, str) and is_shouting(library):
        data["library"] = name_case(library, force_short=True)
    language = data.get("language")
    if isinstance(language, str):
        data["language"] = _LANGUAGES.get(_fold(language.strip()), language)
    return data


#: CAPES stores languages without accents in the uppercase years.
_LANGUAGES = {
    "portugues": "Português",
    "ingles": "Inglês",
    "espanhol": "Espanhol",
    "frances": "Francês",
    "italiano": "Italiano",
    "alemao": "Alemão",
    "japones": "Japonês",
}

_PAREN_SPACES_RE = re.compile(r"\(\s+([^()]*?)\s+\)")


def _tidy_parentheses(value: str) -> str:
    """Turn ``Filho ( FRANCA )`` into ``Filho (Franca)`` before casing.

    Short uppercase content such as ``(UFRJ)`` stays an acronym; longer
    shouting words inside the parentheses (usually a campus city) are
    title-cased.
    """

    def replace(match: re.Match[str]) -> str:
        inner = match.group(1)
        letters = sum(char.isalpha() for char in inner)
        lexicon = _load_lexicon()
        if inner.isupper() and letters >= 5 and _fold(inner) not in lexicon.acronyms:
            inner = name_case(inner, force_short=True)
        return f"({inner})"

    return _PAREN_SPACES_RE.sub(replace, value)


