_ROMAN_RE = re.compile(r"^M{0,3}(CM|CD|D?C{0,3})(XC|XL|L?X{0,3})(IX|IV|V?I{0,3})$")
_PAREN_ACRONYM_RE = re.compile(r"\(([^\W\d_]{2,6})\)", re.UNICODE)
_SENTINEL_RE = re.compile(r"\x00(\d+)\x00")
#: Fragment separators used to truecase each part of a mixed-style title.
_SEGMENT_SEPARATOR_RE = re.compile(r"(\.\s+|:\s+|\s+[-—]\s+|\?\s+|!\s+)")
