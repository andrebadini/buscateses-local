_PROSE_AMBIGUOUS_UFS = frozenset({"SE"})
_PLACE_SEPARATOR_RE = re.compile(r"(?:/|\s[-\u2013\u2014])\s*$")

#: Alphanumeric chunks; hyphens and apostrophes stay inside the chunk so that
