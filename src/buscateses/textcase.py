"""Truecasing helpers for the CAPES catalogue.

The catalogue stores most records in uppercase.  This module restores readable
sentence and name casing for display and embeddings, using a compact lexicon
generated by ``tools/dataset/build_truecase_lexicon.py``.

The public helpers are pure and safe to call in bulk: the lexicon is loaded
lazily and cached, and every function returns the input unchanged when it is
not shouting (so mixed-case user content is never rewritten).
"""

